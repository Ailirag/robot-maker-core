"""A small, deterministic Markdown-to-HTML renderer for the hand-written guides.

The instruction guides keep their prose in Markdown (the owner edits it);
the HTML is generated by regen and gated for freshness, so the two can no
longer drift apart by hand. Only the constructs those documents use are
supported: ATX headings, paragraphs, bullet and numbered lists with
indentation nesting, pipe tables with a separator row, fenced code, bold,
inline code and links. Anything else is rendered as escaped text rather
than guessed. Standard library only.
"""
from __future__ import annotations

import html
import re

_HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
_LIST_ITEM = re.compile(r"^(\s*)([-*]|\d+\.)\s+(.*)$")
_TABLE_SEP = re.compile(r"^\s*\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)*\|?\s*$")
_INLINE_CODE = re.compile(r"`([^`]+)`")
_BOLD = re.compile(r"\*\*(.+?)\*\*")
_LINK = re.compile(r"\[([^\]]+)\]\(([^)\s]+)\)")


def inline(text: str) -> str:
    """Inline markup on an already-raw line: code first so its content is literal."""
    parts = []
    last = 0
    for match in _INLINE_CODE.finditer(text):
        parts.append(_inline_rest(text[last:match.start()]))
        parts.append("<code>" + html.escape(match.group(1)) + "</code>")
        last = match.end()
    parts.append(_inline_rest(text[last:]))
    return "".join(parts)


def _inline_rest(text: str) -> str:
    escaped = html.escape(text, quote=False)
    escaped = _BOLD.sub(r"<b>\1</b>", escaped)
    escaped = _LINK.sub(lambda m: f'<a href="{html.escape(m.group(2), quote=True)}">{m.group(1)}</a>',
                        escaped)
    return escaped


def slug(text: str) -> str:
    text = re.sub(r"<[^>]+>", "", text).lower()
    text = re.sub(r"[^0-9a-zа-яё]+", "-", text).strip("-")
    return text or "section"


def render(markdown: str, *, heading_ids: dict[int, str] | None = None,
           section_level: int = 2, shift: int = 0) -> str:
    """HTML body for ``markdown``.

    Headings of ``section_level`` open ``<section id=...>`` blocks; the id is
    taken from ``heading_ids`` (keyed by the 1-based order of those headings)
    or derived from the text. ``shift`` lowers every heading level, so a
    document's ``#`` can become the guide's ``<h2>``.
    """
    lines = markdown.replace("\r\n", "\n").split("\n")
    out: list[str] = []
    section_open = False
    section_count = 0
    i = 0
    paragraph: list[str] = []

    def flush_paragraph() -> None:
        if paragraph:
            out.append("<p>" + inline(" ".join(s.strip() for s in paragraph)) + "</p>")
            paragraph.clear()

    while i < len(lines):
        line = lines[i]
        stripped = line.strip()
        if not stripped:
            flush_paragraph()
            i += 1
            continue
        raw_block = re.match(r"^<(svg|figure|div|table)\b", stripped)
        if raw_block:
            # Raw HTML blocks (the hub-board SVG diagrams) pass through verbatim
            # up to the matching closing tag on its own line.
            flush_paragraph()
            tag = raw_block.group(1)
            raw: list[str] = []
            while i < len(lines):
                raw.append(lines[i])
                if lines[i].strip().endswith(f"</{tag}>"):
                    i += 1
                    break
                i += 1
            out.append("\n".join(raw))
            continue
        if stripped.startswith("```"):
            flush_paragraph()
            i += 1
            code: list[str] = []
            while i < len(lines) and not lines[i].strip().startswith("```"):
                code.append(lines[i])
                i += 1
            i += 1
            out.append("<pre>" + html.escape("\n".join(code)) + "</pre>")
            continue
        if re.match(r"^\s*(-{3,}|\*{3,})\s*$", line):
            flush_paragraph()
            out.append("<hr>")
            i += 1
            continue
        heading = _HEADING.match(line)
        if heading:
            flush_paragraph()
            level = len(heading.group(1)) + shift
            text = inline(heading.group(2))
            if level == section_level:
                if section_open:
                    out.append("</section>")
                section_count += 1
                ident = (heading_ids or {}).get(section_count) or slug(heading.group(2))
                out.append(f'<section id="{ident}">')
                section_open = True
            out.append(f"<h{level}>{text}</h{level}>")
            i += 1
            continue
        if stripped.startswith("|") and i + 1 < len(lines) and _TABLE_SEP.match(lines[i + 1]):
            flush_paragraph()
            header = [c.strip() for c in stripped.strip("|").split("|")]
            i += 2
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append([c.strip() for c in lines[i].strip().strip("|").split("|")])
                i += 1
            out.append("<table><thead><tr>" + "".join(f"<th>{inline(h)}</th>" for h in header)
                       + "</tr></thead><tbody>"
                       + "".join("<tr>" + "".join(f"<td>{inline(c)}</td>" for c in row) + "</tr>"
                                 for row in rows)
                       + "</tbody></table>")
            continue
        if _LIST_ITEM.match(line):
            flush_paragraph()
            i = _render_list(lines, i, out)
            continue
        paragraph.append(line)
        i += 1
    flush_paragraph()
    if section_open:
        out.append("</section>")
    return "\n".join(out)


def _render_list(lines: list[str], start: int, out: list[str]) -> int:
    """Nested lists by indentation; returns the index after the list."""
    stack: list[tuple[int, str]] = []  # (indent, tag)
    i = start
    while i < len(lines):
        match = _LIST_ITEM.match(lines[i])
        if not match:
            if lines[i].strip() and stack and len(lines[i]) - len(lines[i].lstrip()) > stack[-1][0]:
                # continuation line of the previous item
                out[-1] = out[-1][:-len("</li>")] + " " + inline(lines[i].strip()) + "</li>"
                i += 1
                continue
            break
        indent = len(match.group(1).replace("\t", "    "))
        tag = "ol" if match.group(2)[0].isdigit() else "ul"
        while stack and indent < stack[-1][0]:
            out.append(f"</{stack.pop()[1]}>")
        if not stack or indent > stack[-1][0]:
            out.append(f"<{tag}>")
            stack.append((indent, tag))
        elif stack[-1][1] != tag:
            out.append(f"</{stack.pop()[1]}>")
            out.append(f"<{tag}>")
            stack.append((indent, tag))
        out.append("<li>" + inline(match.group(3)) + "</li>")
        i += 1
    while stack:
        out.append(f"</{stack.pop()[1]}>")
    return i
